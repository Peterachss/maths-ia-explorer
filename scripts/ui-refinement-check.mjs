import { chromium } from 'playwright';
const browser = await chromium.launch({channel:'chrome'});
const page = await browser.newPage({viewport:{width:1440,height:900}});
page.on('requestfailed', r => console.log('FAILED', r.url(), r.failure()?.errorText));
page.on('pageerror', e => console.log('ERROR', String(e)));
await page.goto('http://127.0.0.1:5174/?c=ZWE%2CSGP');
await page.waitForTimeout(18000);
await page.screenshot({path:'docs/screens/desktop-hero.png'});
const search = page.locator('input[role=combobox]');
await search.scrollIntoViewIfNeeded();
await search.fill('zzzz');
if (!(await page.getByText('No countries match', {exact:false}).isVisible())) throw Error('No-match state missing');
await search.fill('united');
await search.press('ArrowDown');
console.log('ACTIVE', await search.getAttribute('aria-activedescendant'));
await search.press('Enter');
if ((await search.inputValue()) !== '') throw Error('Search did not clear');
console.log('SEARCH PASS', page.url());
await browser.close();
